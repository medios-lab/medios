template <>
struct hash<medios::ContainerID>
{
  typedef size_t result_type;

  typedef medios::ContainerID argument_type;

  result_type operator()(const argument_type& containerId) const
  {
    size_t seed = 0;
    boost::hash_combine(seed, containerId.value());

    if (containerId.has_parent()) {
      boost::hash_combine(
          seed,
          std::hash<medios::ContainerID>()(containerId.parent()));
    }

    return seed;
  }
};


